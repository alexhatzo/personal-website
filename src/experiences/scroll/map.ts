function inside([x, y]: Pt, poly: Pt[]) {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

// One <path> of zero-length segments; round caps turn each into a dot.
export function dotPath(step = 1.5) {
  let d = "";
  for (let lat = LAT1 - step / 2; lat > LAT0; lat -= step) {
    const row = Math.round((LAT1 - lat) / step);
    const lonStep = step / COS;
    for (let lon = LON0 + (row % 2 ? lonStep / 2 : 0); lon < LON1; lon += lonStep) {
      const p: Pt = [lon, lat];
      if (LAND.some((l) => inside(p, l)) && !WATER.some((w) => inside(p, w))) {
        const [x, y] = project(p);
        d += `M${x.toFixed(1)} ${y.toFixed(1)}h0`;
      }
    }
  }
  return d;
}

export const ATH: Pt = [23.94, 37.94];
export const LAX: Pt = [-118.41, 33.94];

// Slerp along the great circle, projected to map space.
export function routePoints(n = 140): [number, number][] {
  const r = Math.PI / 180;
  const v = ([lo, la]: Pt) => [Math.cos(la * r) * Math.cos(lo * r), Math.cos(la * r) * Math.sin(lo * r), Math.sin(la * r)];
  const a = v(ATH), b = v(LAX);
  const d = Math.acos(a[0] * b[0] + a[1] * b[1] + a[2] * b[2]);
  const out: [number, number][] = [];
  for (let i = 0; i <= n; i++) {
    const t = i / n, A = Math.sin((1 - t) * d) / Math.sin(d), B = Math.sin(t * d) / Math.sin(d);
    const p = a.map((x, k) => A * x + B * b[k]);
    out.push(project([Math.atan2(p[1], p[0]) / r, Math.asin(p[2]) / r]));
  }
  return out;
}
